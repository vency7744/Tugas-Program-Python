# Program Pengolahan Data 5 Mahasiswa

jumlah_lulus = 0        # counter mahasiswa LULUS
jumlah_tidak_lulus = 0  # counter mahasiswa TIDAK LULUS

print("=== INPUT DATA MAHASISWA ===")

for i in range(1, 6):  # tepat 5 mahasiswa
    print(f"\nMahasiswa ke-{i}")
    nama = input("Nama mahasiswa          : ")
    tugas = float(input("Nilai tugas            : "))
    uts = float(input("Nilai UTS              : "))
    kehadiran = float(input("Persentase kehadiran (%): "))

    # Hitung nilai akhir
    nilai_akhir = 0.4 * tugas + 0.6 * uts

    # Tentukan kategori nilai (if-elif-else)
    if nilai_akhir >= 85:
        kategori = "A"
    elif nilai_akhir >= 75:
        kategori = "B"
    elif nilai_akhir >= 65:
        kategori = "C"
    elif nilai_akhir >= 55:
        kategori = "D"
    else:
        kategori = "E"

    # Tentukan status (kondisi majemuk)
    if nilai_akhir >= 65 and kehadiran >= 75:
        status = "LULUS"
        jumlah_lulus += 1
    else:
        status = "TIDAK LULUS"
        jumlah_tidak_lulus += 1

    # Tampilkan hasil per mahasiswa
    print("\n" + "-" * 30)
    print(f"Nama        : {nama}")
    print(f"Nilai Akhir : {nilai_akhir:.1f}")
    print(f"Kategori    : {kategori}")
    print(f"Status      : {status}")

    # Nested if: catatan jika tidak lulus karena kehadiran
    if status == "TIDAK LULUS":
        if kehadiran < 75:
            print("Catatan     : Kehadiran perlu diperbaiki")
    print("-" * 30)

# Rekap akhir
print("\n=== REKAP AKHIR ===")
print(f"Jumlah mahasiswa LULUS       : {jumlah_lulus}")
print(f"Jumlah mahasiswa TIDAK LULUS : {jumlah_tidak_lulus}")